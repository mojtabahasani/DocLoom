/**
 * Localize a command palette entry while keeping Persian text searchable in keywords.
 */
export function localizeCommand(cmd, lang = 'en') {
  if (!cmd || normalizeLang(lang) === 'fa') return cmd;
  let title = CMD_I18N[cmd.id] || cmd.title;
  if (cmd.id?.startsWith('brand-use-') && cmd.title?.startsWith('برند: ')) {
    title = 'Brand: ' + cmd.title.slice(6);
  }
  const group = CMD_GROUP_I18N[cmd.group] || cmd.group;
  const keywords = [cmd.keywords, cmd.title, cmd.group].filter(Boolean).join(' ');
  return { ...cmd, title, group, keywords };
}
