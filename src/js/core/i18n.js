/** Normalize any input into a supported UI language ('en' or 'fa', defaulting to 'en'). */
export function normalizeLang(lang) {
  return lang === 'fa' ? 'fa' : 'en';
}

/** Layout direction for the active UI language. */
export function dirForLang(lang) {
  return normalizeLang(lang) === 'fa' ? 'rtl' : 'ltr';
}

